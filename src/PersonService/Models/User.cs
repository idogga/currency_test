using System.ComponentModel.DataAnnotations.Schema;

namespace PersonService.Models;

/// <summary>
/// Пользователь.
/// </summary>
[Table("user")]
public record User
{
    /// <summary>
    /// Идентификатор пользователя.
    /// </summary>
    public Guid Id { get; set; }

    /// <summary>
    /// Имя пользователя.
    /// </summary>
    public string Name { get; set; } = null!;

    /// <summary>
    /// Пароль пользователя.
    /// </summary>
    public string Password { get; set; } = null!;
}